class Command(BaseCommand):
    help = "Seeds database with supported Indian and international languages."

    def handle(self, *args, **options):
        self.stdout.write("Seeding languages registry...")
        created_count = 0
        updated_count = 0

        for item in LANGUAGES_DATA:
            code = item["code"]
            defaults = {k: v for k, v in item.items() if k != "code"}
            obj, created = Language.objects.update_or_create(code=code, defaults=defaults)
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Successfully seeded languages. Created: {created_count}, Updated: {updated_count}, Total: {len(LANGUAGES_DATA)}"
            )
        )
